// French (français). Loaded only when French is the language (js/i18n.js). Every key is the same
// as in js/i18n/en.js and the data files; a key missing here shows in English.
// Voice: always "tu", factual, no guilt or pressure, no emoji; characters never speak.
// The user's gender is unknown, so nothing agrees with it: past tenses use avoir ("tu as décroché",
// never "tu t'es arrêté"), no adjective or participle describes the user ("prêt", "distrait",
// "concentré"...), and there are no "·e" or "(e)" forms. Sentences are reworded around nouns,
// infinitives or the present tense instead (e.g. "Fin anticipée", "Bon retour !").
// Names, modes or durations inside a text ({name}, {mode}, {duration}) never get an article,
// an elision or an agreement: custom names can be anything, so the sentences are built around
// them (e.g. "en mode {mode}", "(prévu : {duration})").
// "séance" is a session. Apostrophes are the plain ' everywhere.
// \u202f is a narrow no-break space: French puts it before ? ! : ; and % and inside « », so the
// sign never wraps onto its own line. \u00a0 is a no-break space: a number and its unit stay on
// one line. \u00ad is a soft hyphen: an invisible break point in a long word ("Biblio\u00adthécaire"),
// so a narrow card breaks it there, with a hyphen, instead of anywhere. Screen readers ignore it.
// See "Languages" in the README.

