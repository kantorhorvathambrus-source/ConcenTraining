// "Abgelenkt?" or "du bist zurückgekommen" are fine.
// Names, modes or durations inside a text ({name}, {mode}, {duration}) never get an article, a
// case ending or a genitive -s: custom names can be anything, so the sentences are built around
// them ("{name} löschen?", "Kostüm anziehen: {name}").
// Units: "Min.", "Sek.", "Std."; a percentage is "25 %" (with a no-break space).
// \u00a0 is a no-break space: a number and its unit always stay on one line.
// \u00ad is a soft hyphen: an invisible break point in a long compound word ("Lern\u00adkumpel"),
// so a narrow card breaks it there, with a hyphen, instead of anywhere. Screen readers ignore it.
// See "Languages" in the README.

